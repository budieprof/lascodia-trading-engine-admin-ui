/**
 * Generates `src/app/core/auth/permissions.generated.ts` from `docs/permission-catalog.json`.
 *
 *   node scripts/generate-permissions.mjs           # write the module
 *   node scripts/generate-permissions.mjs --check   # exit 1 when the module is stale (CI / pre-release)
 *
 * `docs/permission-catalog.json` is a CHECKED-IN COPY of the engine's `docs/permission-catalog.json`
 * (multi-tenancy contract C3.4: `[{key,category,description,scopeable,stepUp,twoPerson,deprecated}]`,
 * the same list `GET /admin/permissions/catalog` serves; an engine unit test keeps the engine's file
 * equal to its catalog). Refreshing it is a copy + regenerate:
 *
 *   cp ../lascodia-trading-engine/docs/permission-catalog.json docs/permission-catalog.json
 *   npm run permissions:generate
 *
 * A key the console uses that disappears from the catalog then fails the typecheck where it is used —
 * deliberately: a page gated on a key the engine no longer knows would be gated on nothing.
 *
 * The input is validated strictly (shape, key syntax, duplicates); a malformed catalog fails the run
 * rather than producing a module that gates on garbage.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG_PATH = join(ROOT, 'docs', 'permission-catalog.json');
export const OUTPUT_PATH = join(ROOT, 'src', 'app', 'core', 'auth', 'permissions.generated.ts');

/** `<resource>.<action>` segments: lowercase letters, digits and underscores (ADR-0031 §1). */
const KEY_PATTERN = /^[a-z0-9_]+(\.[a-z0-9_]+)+$/;
const FLAGS = ['scopeable', 'stepUp', 'twoPerson', 'deprecated'];

/**
 * Validates the parsed catalog and returns its entries sorted by key (stable output whatever order
 * the engine wrote them in). Throws with every problem found, not just the first.
 */
export function validateCatalog(raw) {
  if (!Array.isArray(raw)) throw new Error('permission catalog: expected a JSON array');
  const problems = [];
  const seen = new Set();
  const entries = [];
  raw.forEach((e, i) => {
    const where = `entry ${i}${e && typeof e.key === 'string' ? ` (${e.key})` : ''}`;
    if (!e || typeof e !== 'object' || Array.isArray(e)) {
      problems.push(`${where}: not an object`);
      return;
    }
    if (typeof e.key !== 'string' || !KEY_PATTERN.test(e.key)) problems.push(`${where}: bad key`);
    if (typeof e.category !== 'string' || e.category.trim() === '') problems.push(`${where}: bad category`);
    if (typeof e.description !== 'string') problems.push(`${where}: bad description`);
    for (const f of FLAGS) if (typeof e[f] !== 'boolean') problems.push(`${where}: ${f} must be a boolean`);
    if (typeof e.key === 'string') {
      if (seen.has(e.key)) problems.push(`${where}: duplicate key`);
      seen.add(e.key);
    }
    entries.push({
      key: e.key,
      category: e.category,
      description: e.description,
      scopeable: e.scopeable,
      stepUp: e.stepUp,
      twoPerson: e.twoPerson,
      deprecated: e.deprecated,
    });
  });
  if (problems.length) throw new Error(`permission catalog is invalid:\n  ${problems.join('\n  ')}`);
  if (entries.length === 0) throw new Error('permission catalog is empty');
  return entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** `iam.access_review` → `IamAccessReview`; `orders.cancel.batch` → `OrdersCancelBatch`. */
export function identifierFor(key) {
  return key
    .split(/[._]/)
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

function quote(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n')}'`;
}

/** Renders the TypeScript module for already-validated entries (unformatted; prettier runs after). */
export function renderModule(entries) {
  const ids = new Map();
  for (const e of entries) {
    const id = identifierFor(e.key);
    if (ids.has(id)) throw new Error(`keys ${ids.get(id)} and ${e.key} both map to ${id}`);
    ids.set(id, e.key);
  }
  const rows = entries
    .map(
      (e) =>
        `  { key: ${quote(e.key)}, category: ${quote(e.category)}, description: ${quote(e.description)}, ` +
        `scopeable: ${e.scopeable}, stepUp: ${e.stepUp}, twoPerson: ${e.twoPerson}, deprecated: ${e.deprecated} },`,
    )
    .join('\n');
  const named = entries.map((e) => `  ${identifierFor(e.key)}: ${quote(e.key)},`).join('\n');
  return `// GENERATED by scripts/generate-permissions.mjs from docs/permission-catalog.json — do not edit.
// That JSON is a copy of the engine's docs/permission-catalog.json (contract C3.4). To refresh:
//   cp ../lascodia-trading-engine/docs/permission-catalog.json docs/permission-catalog.json
//   npm run permissions:generate

/** One catalog entry (engine \`PermissionDefinition\`, ADR-0031 §1). */
export interface PermissionDefinition {
  readonly key: string;
  readonly category: string;
  readonly description: string;
  /** Can be granted below organisation level (account group, trading account, strategy). */
  readonly scopeable: boolean;
  /** Needs a fresh sign-in with a second factor (contract C3.2). */
  readonly stepUp: boolean;
  /** Needs a second person's approval (contract C3.3). */
  readonly twoPerson: boolean;
  /** Still enforced, but give the specific keys instead. */
  readonly deprecated: boolean;
}

/** Every permission the engine knows, sorted by key. */
export const PERMISSION_CATALOG = [
${rows}
] as const satisfies readonly PermissionDefinition[];

/** A permission key the engine knows. */
export type PermissionKey = (typeof PERMISSION_CATALOG)[number]['key'];

/** Named constants for every key: \`Permission.OrdersRead === 'orders.read'\`. */
export const Permission = {
${named}
} as const satisfies Record<string, PermissionKey>;

const KEYS: ReadonlySet<string> = new Set(PERMISSION_CATALOG.map((p) => p.key));

/** True when \`value\` is a key in this catalog (a server may know keys a stale console does not). */
export function isPermissionKey(value: string): value is PermissionKey {
  return KEYS.has(value);
}

/** The catalog entry for a key, or undefined for a key this console does not know. */
export function permissionDefinition(key: string): PermissionDefinition | undefined {
  return PERMISSION_CATALOG.find((p) => p.key === key);
}
`;
}

/** Formats with the repo's prettier config so lint-staged leaves the committed file alone. */
async function format(source) {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(OUTPUT_PATH)) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
}

export async function generate() {
  const raw = JSON.parse(await readFile(CATALOG_PATH, 'utf8'));
  return format(renderModule(validateCatalog(raw)));
}

async function main() {
  const check = process.argv.includes('--check');
  const next = await generate();
  if (check) {
    const current = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
    if (current !== next) {
      console.error(
        'permissions.generated.ts is stale — run `npm run permissions:generate` and commit the result.',
      );
      process.exit(1);
    }
    console.log('permissions.generated.ts is up to date.');
    return;
  }
  await writeFile(OUTPUT_PATH, next);
  console.log(`wrote ${OUTPUT_PATH}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
