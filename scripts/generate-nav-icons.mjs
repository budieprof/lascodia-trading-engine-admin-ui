#!/usr/bin/env node
/**
 * Writes src/app/layout/sidebar/nav-icons.ts: the drawing data of every Lucide icon the sidebar
 * uses, copied from the installed @lucide/angular.
 *
 * Why not import the icon components: each one is a full Angular component whose compiled
 * template (~3.3 kB minified) is repeated per icon, so the sidebar's 116 icons added ~390 kB to the
 * initial bundle. The sidebar draws them all through the one LucideDynamicIcon instead, which takes
 * plain LucideIconData — a few hundred bytes per icon.
 *
 * Usage: reference an icon as `navIcon.<LucideName>` (PascalCase, as on lucide.dev without dashes:
 * `navIcon.ClipboardList`) in nav-items.ts or sidebar.component.ts, then
 *   node scripts/generate-nav-icons.mjs
 * Re-run after upgrading @lucide/angular. A name the generator cannot find fails the run; a name
 * that is used but not generated fails the TypeScript build.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  'src/app/layout/sidebar/nav-items.ts',
  'src/app/layout/sidebar/sidebar.component.ts',
];
const out = join(root, 'src/app/layout/sidebar/nav-icons.ts');
const pkg = join(root, 'node_modules/@lucide/angular');

const used = new Set();
for (const file of sources) {
  for (const m of readFileSync(join(root, file), 'utf8').matchAll(
    /\bnavIcon\.([A-Z][A-Za-z0-9]*)/g,
  )) {
    used.add(m[1]);
  }
}

const lib = readFileSync(join(pkg, 'fesm2022/lucide-angular.mjs'), 'utf8');
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;

/** The object literal after `static icon = ` in `class Lucide<name> extends LucideIconBase`. */
function iconData(name) {
  const head = `class Lucide${name} extends LucideIconBase {`;
  const at = lib.indexOf(head);
  if (at < 0)
    throw new Error(
      `No Lucide icon "${name}" in @lucide/angular ${version} (aliases are not supported: use the canonical name)`,
    );
  const start = lib.indexOf('static icon = ', at) + 'static icon = '.length;
  let depth = 0;
  for (let i = start; i < lib.length; i++) {
    if (lib[i] === '{') depth++;
    else if (lib[i] === '}' && --depth === 0) {
      // Plain data (strings, numbers, arrays, objects) — evaluated, then re-serialised as JSON.
      return new Function(`return (${lib.slice(start, i + 1)});`)();
    }
  }
  throw new Error(`Unbalanced icon data for ${name}`);
}

const names = [...used].sort();
const body = names.map((n) => `  ${n}: ${JSON.stringify(iconData(n))},`).join('\n');
writeFileSync(
  out,
  `// GENERATED by scripts/generate-nav-icons.mjs from @lucide/angular ${version}. Do not edit by hand:
// reference the icon as navIcon.<Name> in nav-items.ts or sidebar.component.ts and re-run the script.
import type { LucideIconData } from '@lucide/angular';

export const navIcon = {
${body}
} satisfies Record<string, LucideIconData>;
`,
);
// Formatted like the rest of the repo, so a re-run with unchanged icons leaves no diff.
execFileSync(join(root, 'node_modules/.bin/prettier'), ['--write', out], { stdio: 'ignore' });
console.log(`nav-icons.ts: ${names.length} icons from @lucide/angular ${version}`);
